use core::time::Duration;

use fraktor_actor::kernel::pretty_duration::PrettyDurationInput;

fn finite(nanos: u64) -> PrettyDurationInput {
  PrettyDurationInput::Finite(Duration::from_nanos(nanos))
}

#[test]
fn pretty_duration_prints_9_nanos() {
  assert_eq!(finite(9).pretty(), "9.000 ns");
}

#[test]
fn pretty_duration_prints_95_nanos() {
  assert_eq!(finite(95).pretty(), "95.00 ns");
}

#[test]
fn pretty_duration_prints_999_nanos() {
  assert_eq!(finite(999).pretty(), "999.0 ns");
}

#[test]
fn pretty_duration_prints_1000_nanos_as_micros() {
  assert_eq!(finite(1_000).pretty(), "1.000 μs");
}

#[test]
fn pretty_duration_prints_9500_nanos() {
  assert_eq!(finite(9_500).pretty(), "9.500 μs");
}

#[test]
fn pretty_duration_prints_9500_micros_as_millis() {
  assert_eq!(finite(9_500_000).pretty(), "9.500 ms");
}

#[test]
fn pretty_duration_prints_9500_millis_as_seconds() {
  assert_eq!(finite(9_500_000_000).pretty(), "9.500 s");
}

#[test]
fn pretty_duration_prints_95_seconds_as_minutes() {
  assert_eq!(finite(95_000_000_000).pretty(), "1.583 min");
}

#[test]
fn pretty_duration_prints_95_minutes_as_hours() {
  assert_eq!(finite(95 * 60_000_000_000).pretty(), "1.583 h");
}

#[test]
fn pretty_duration_prints_95_hours_as_days() {
  assert_eq!(finite(95 * 3_600_000_000_000).pretty(), "3.958 d");
}

#[test]
fn pretty_duration_works_with_infinity() {
  assert!(PrettyDurationInput::Infinite.pretty().contains("infinity"));
}

#[test]
fn pretty_duration_works_with_minus_infinity() {
  assert!(PrettyDurationInput::MinusInfinite.pretty().contains("minus infinity"));
}

#[test]
fn pretty_duration_works_with_undefined() {
  assert!(PrettyDurationInput::Undefined.pretty().contains("undefined"));
}
